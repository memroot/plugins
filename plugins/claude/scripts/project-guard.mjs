var MEMORY_TOOL = named(MCP_PROJECT_TOOL_NAMES_V1);
var record = (value) => value && typeof value === "object" && !Array.isArray(value) ? value : void 0;
function decide(decision, reason, input) {
  process.stdout.write(
    `${JSON.stringify({
      hookSpecificOutput: {
        hookEventName: "PreToolUse",
        permissionDecision: decision,
        permissionDecisionReason: reason,
        ...input ? { updatedInput: input } : {}
      }
    })}
`
  );
}
function grokArguments(input) {
  if (typeof input.tool_name !== "string" || !("tool_input" in input))
    return input;
  return record(input.tool_input);
}
function unparsedInputWrapper(args) {
  if (!args) return false;
  return "__unparsedToolInput" in args || "raw" in args && "len" in args;
}
async function main() {
  const event = await readEnvelope();
  if (inertProcess() || !event) return;
  const name = event.tool_name ?? event.toolName;
  if (typeof name !== "string") return;
  if (process.env.MEMROOT_IMPORT_RUN === "1") {
    const wrapped = record(event.tool_input ?? event.toolInput)?.tool_name;
    const tool2 = name === "use_tool" && typeof wrapped === "string" ? wrapped : name;
    if (ANY_MEMROOT_TOOL.test(tool2) && !IMPORT_TOOL.test(tool2)) {
      decide(
        "deny",
        "This memroot import run may only save memories with memory_create; other Memroot tools are not available in it."
      );
      return;
    }
  }
  const input = record(event.tool_input ?? event.toolInput) ?? {};
  const tool = name === "use_tool" && typeof input.tool_name === "string" ? input.tool_name : name;
  if (ANY_MEMROOT_TOOL.test(tool) && unparsedInputWrapper(
    hostAgent("claude") === "grok" ? grokArguments(input) : input
  )) {
    memroot = true;
    decide(
      "deny",
      "The tool arguments were a replayed unparsed-input wrapper ({raw, len}), not the documented arguments. Compose the call again with the documented arguments (call memory_request_schema first if needed); never re-send the wrapper."
    );
    return;
  }
  if (READ_ONLY_TOOL.test(tool)) {
    decide("allow", "Read-only Memroot tool; it takes no project.");
    return;
  }
  if (!MEMORY_TOOL.test(tool)) return;
  memroot = true;
  const selected = effectiveProject(
    process.env.MEMROOT_IMPORT_RUN === "1" ? void 0 : eventFolder(event)
  );
  const command = projectCommandPrefix();
  if (!selected) {
    decide(
      "deny",
      `No Memroot project is selected on this computer. Run: ${command} use (it selects the only project, or lists them; then ${command} use "<name>"), then retry.`
    );
    return;
  }
  if (selected.stale) {
    decide("deny", `${staleBindingText(selected)} Then retry.`);
    return;
  }
  const folder = selected.scope === "folder";
  const reason = folder ? `Memroot memory call for the project bound to this folder (${selected.projectId}).` : `Memroot memory call for the project selected on this computer (${selected.projectId}).`;
  if (hostAgent("claude") === "grok") {
    if (grokArguments(input)?.project_id === selected.projectId)
      decide("allow", reason);
    else
      decide(
        "deny",
        `Use the Memroot project ${folder ? "bound to this folder" : "selected on this computer"}: retry with project_id "${selected.projectId}" in the tool arguments.`
      );
    return;
  }
  decide("allow", reason, { ...input, project_id: selected.projectId });
}
main().catch(() => {
  if (!memroot) return;
  decide(
    "deny",
    "Memroot could not read the project selected on this computer. Run the Memroot project command with use, then retry."
  );
}).finally(() => process.exit(0));
